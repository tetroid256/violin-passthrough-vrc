    public static bool IsSupported(char c) => Glyphs.ContainsKey(char.ToUpperInvariant(c));

    /// <summary>文字列の幅（フォントの点の数、余白込み）。</summary>
    public static int MeasureDots(string text) =>
        Math.Max(0, text.Length * (GlyphWidth + Spacing) - Spacing) + 2 * Padding;

    /// <summary>
    /// 文字列を描く。1 つの点を <paramref name="scale"/> × <paramref name="scale"/> 画素で描き、周りを背景色で塗る。
    /// </summary>
    public static MaskTexture Render(
        string text,
        (byte R, byte G, byte B, byte A) foreground,
        (byte R, byte G, byte B, byte A) background,
        int scale = 4)
    {
        scale = Math.Clamp(scale, 1, 32);
        var width = MeasureDots(text) * scale;
        var height = (GlyphHeight + 2 * Padding) * scale;
        var rgba = new byte[width * height * 4];
        for (var i = 0; i < rgba.Length; i += 4)
        {
            rgba[i] = background.R;
            rgba[i + 1] = background.G;
            rgba[i + 2] = background.B;
            rgba[i + 3] = background.A;
        }

        for (var c = 0; c < text.Length; c++)
        {
            var glyph = Glyphs.GetValueOrDefault(char.ToUpperInvariant(text[c])) ?? Glyphs['?'];
            var originX = Padding + c * (GlyphWidth + Spacing);
            for (var gy = 0; gy < GlyphHeight; gy++)
            {
                for (var gx = 0; gx < GlyphWidth; gx++)
                {
                    if (glyph[gy][gx] != '#')
                    {
                        continue;
                    }

                    for (var sy = 0; sy < scale; sy++)
                    {
                        var row = (Padding + gy) * scale + sy;
                        for (var sx = 0; sx < scale; sx++)
                        {
                            var i = (row * width + (originX + gx) * scale + sx) * 4;
                            rgba[i] = foreground.R;
                            rgba[i + 1] = foreground.G;
                            rgba[i + 2] = foreground.B;
                            rgba[i + 3] = foreground.A;
                        }
                    }
                }
            }
        }

        return new MaskTexture(width, height, rgba);
    }
}
