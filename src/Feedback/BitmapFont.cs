using ViolinPassthrough.Mask;

namespace ViolinPassthrough.Feedback;

/// <summary>
/// 通知表示用の 5×7 ドットのフォント（英大文字・数字・一部の記号）。小文字は大文字にし、知らない文字は「?」にする。
/// 外部のフォントや描画ライブラリに頼らず、テストでも同じ結果になるようにする。
/// </summary>
public static class BitmapFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;

    /// <summary>文字の間の空き（フォントの点の数）。</summary>
    public const int Spacing = 1;

    /// <summary>文字列の周りの余白（フォントの点の数）。</summary>
    public const int Padding = 2;

